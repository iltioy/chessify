const LANG = (() => {
  try {
    const saved = localStorage.getItem("chessify-lang");
    if (saved === "ru" || saved === "en") return saved;
  } catch { /* хранилище недоступно */ }
  const nav = (navigator.language || "").toLowerCase();
  return ["ru", "uk", "be", "kk", "ky", "uz"].some((p) => nav.startsWith(p)) ? "ru" : "en";
})();

function t(key, vars = {}) {
  const text = I18N[LANG][key] ?? I18N.ru[key] ?? key;
  return text.replace(/\{(\w+)\}/g, (_, k) => (k in vars ? vars[k] : `{${k}}`));
}

// Подписи в разметке: data-i18n — текст, data-i18n-ph — placeholder, data-i18n-title — подсказка.
function applyI18n(root = document) {
  root.querySelectorAll("[data-i18n]").forEach((n) => { n.textContent = t(n.dataset.i18n); });
  root.querySelectorAll("[data-i18n-ph]").forEach((n) => { n.placeholder = t(n.dataset.i18nPh); });
  root.querySelectorAll("[data-i18n-title]").forEach((n) => { n.title = t(n.dataset.i18nTitle); });
  root.querySelectorAll("[data-i18n-aria]").forEach((n) => { n.setAttribute("aria-label", t(n.dataset.i18nAria)); });
}

function setLang(lang) {
  try { localStorage.setItem("chessify-lang", lang); } catch { /* хранилище недоступно */ }
  location.reload(); // проще и надёжнее, чем перерисовывать каждую часть страницы
}

document.documentElement.lang = LANG;
